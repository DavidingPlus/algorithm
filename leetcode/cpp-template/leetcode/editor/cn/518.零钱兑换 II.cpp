class Solution
{

public:

    // 典型的完全背包问题。
    int change(int amount, const std::vector<int> &coins)
    {
        int m = coins.size(), n = amount;

        // 使用滚动数组优化空间复杂度，逻辑请从二维考虑。
        // XXX LeetCode 的叼毛数据，它保证最后返回的答案是不溢出的，但是过程中值可能溢出，从这个角度讲，过程中的这些溢出的值与最后的答案没关系，可以不按正确值存储。labuladong 直接用 unsigned int 存储，溢出直接循环到 0 了，666 绷不住了。
        std::vector<unsigned int> dp(1 + n, 0);
        // 初始条件，不用任何硬币凑出 0 面额有 1 种方法。考虑 [1] 凑出 1 的过程，即可反推出此条件。
        dp[0] = 1;


        for (int i = 1; i <= m; ++i)
        {
            std::vector<unsigned int> tmp(1 + n, 0);
            tmp[0] = 1;

            for (int j = 1; j <= n; ++j)
            {
                tmp[j] = dp[j];

                if (j - coins[i - 1] >= 0) tmp[j] += tmp[j - coins[i - 1]];
            }

            std::swap(dp, tmp);
        }


        return static_cast<int>(dp[n]);
    }
};

